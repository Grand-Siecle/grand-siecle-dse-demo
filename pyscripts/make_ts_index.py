"""Index the Grand Siecle editions in Typesense: one search document per printed page.

Adapted from the template's make_ts_index.py (one document per TEI file, fields title /
full_text / *_entities). Here, as in the reading view (xslt/editions.xsl), pages are cut on
tei:pb; each page carries both text layers, the lemmas, the named entities per type (labels
from the source registers in data/indices) and a few facets. The TEI of data/editions are
read as they are: page n = rank of the pb (the pb carry no @n), document id from the file
name (LIV0019_reconciled.tei.xml -> LIV0019), sourceDoc and standOff ignored. Schema: see docs/04-plateforme-commune-typesense.md §4.2
in grand-siecle-max-statique.

The script also creates a search-only API key restricted to the collection and writes the
browser configuration html/js/search-config.js (gitignored). The admin key never goes to html/.

Configuration (environment):
  TYPESENSE_HOST / TYPESENSE_PORT / TYPESENSE_PROTOCOL   server used for indexing (localhost:8108 http)
  TYPESENSE_API_KEY                                      admin key (required)
  TYPESENSE_COLLECTION                                   collection name (grand-siecle-dse)
  TYPESENSE_PUBLIC_HOST / _PORT / _PROTOCOL              server as seen by the browser (default: same)

Usage: TYPESENSE_API_KEY=... uv run pyscripts/make_ts_index.py
"""

import glob
import json
import os
import re
import sys
import time
from pathlib import Path

import typesense
from lxml import etree
from typesense.exceptions import ObjectNotFound

TEI = "http://www.tei-c.org/ns/1.0"
NS = {"tei": TEI}
XML_ID = "{http://www.w3.org/XML/1998/namespace}id"
XML_LANG = "{http://www.w3.org/XML/1998/namespace}lang"
ROOT = Path(__file__).resolve().parent.parent
CONFIG_JS = ROOT / "html" / "js" / "search-config.js"
KEY_DESCRIPTION = "grand-siecle-dse search-only key (generated by make_ts_index.py)"

LANG_LABELS = {"fra": "français", "lat": "latin", "grc": "grec ancien", "ita": "italien"}
# entity type (prefix of @ref) -> search document field
ENTITY_FIELDS = {
    "person": "persons", "place": "places", "org": "orgs", "work": "works",
    "event": "events", "artwork": "artworks", "material": "materials",
    "technique": "techniques", "date": "dates",
}
ENTITY_TAGS = {f"{{{TEI}}}{t}" for t in
               ("persName", "placeName", "orgName", "rs", "objectName", "material", "title", "date")}
# display rule of xslt/partials/doc_meta.xsl (gsdoc:forename-fixes): the teiHeader of LIV0001
# gives the author's forename as "s"; the site shows "Judocus". Not a correction of the TEI.
AUTHOR_FORENAME_FIXES = {"LIV0001": "Judocus"}


def t_(name):
    return f"{{{TEI}}}{name}"


def env(name, default=None):
    value = os.environ.get(name, default)
    if value is None:
        sys.exit(f"ERROR: environment variable {name} is required")
    return value


def tag(el):
    return el.tag if isinstance(el.tag, str) else ""


def text_of(el):
    return " ".join("".join(el.itertext()).split())


def register_labels():
    """xml:id -> display label, from the 9 source registers (same label as the entity page).
    Every register entry is read; only the ids cited by the texts are used, and these are the
    entries published by the site (its perimeter)."""
    labels = {}
    for path in glob.glob(str(ROOT / "data" / "indices" / "*.xml")):
        for entry in etree.parse(path).iter():
            eid = entry.get(XML_ID) if isinstance(entry.tag, str) else None
            if not eid or not re.fullmatch(r"[a-z]+-\d{6}", eid):
                continue
            names = entry.xpath(
                "(tei:catDesc/tei:term[@type='main'] | *[@type='main'] | tei:date[not(@type)])[normalize-space()]",
                namespaces=NS)
            labels[eid] = text_of(names[0]) if names else eid
    return labels


class LayerText:
    """Text of one layer (orig or reg) of a page, rebuilt from w/pc tokens and text nodes."""

    def __init__(self, layer):
        self.skip = t_("reg" if layer == "orig" else "orig")
        self.parts = []
        self.glue = False  # previous token asks to be glued (hyphenated word, pc join=right)

    def token(self, text, left=False):
        elided = self.parts and self.parts[-1].endswith(("’", "'"))  # qu’il, not qu’ il
        if self.parts and not (left or self.glue or elided):
            self.parts.append(" ")
        self.parts.append(text)
        self.glue = False

    def walk(self, el):
        t = tag(el)
        if t == self.skip:
            return
        if t == t_("w"):
            self.token(text_of(el))
            self.glue = el.get("next") is not None  # word continues on the next line
            return
        if t == t_("pc"):
            self.token(text_of(el), left=el.get("join") == "left")
            self.glue = el.get("join") == "right"
            return
        if t == t_("lb") and not self.glue:
            self.parts.append(" ")
        if el.text and el.text.strip():
            self.parts.append(el.text)
        for child in el:
            self.walk(child)
            if child.tail and child.tail.strip():
                self.parts.append(child.tail)

    def value(self):
        return " ".join("".join(self.parts).split()).replace("’", "'")


def clean_lemma(lemma):
    # same filter as the MaX tooltip: no tool markers (@card), letters required, "sum1" -> "sum"
    if not lemma or lemma.startswith("@") or not re.search(r"[^\W\d_]", lemma):
        return None
    return re.sub(r"(\D)\d+$", r"\1", lemma)


def doc_id_of(path):
    """LIV0019_reconciled.tei.xml -> LIV0019 (same rule as gsdoc:id-from-uri in xslt/partials/doc_meta.xsl)"""
    return re.sub(r"(_reconciled)?(\.tei)?\.xml$", "", Path(path).name)


def page_records(path, labels):
    tree = etree.parse(path, etree.XMLParser(huge_tree=True))
    doc_id = doc_id_of(path)
    header = tree.find(t_("teiHeader"))
    title = " ".join(header.findtext("tei:fileDesc/tei:titleStmt/tei:title", namespaces=NS).split())
    pn = header.find("tei:fileDesc/tei:titleStmt/tei:author/tei:persName", NS)
    names = []
    for x in pn if pn is not None else ():
        if tag(x) == t_("forename"):
            names.append(AUTHOR_FORENAME_FIXES.get(doc_id) or text_of(x))
        elif tag(x) == t_("surname"):
            names.append(text_of(x))
    author = " ".join(names)
    year = re.search(r"\d{4}", header.findtext("tei:fileDesc/tei:sourceDesc/tei:bibl/tei:date",
                                               default="", namespaces=NS) or "")
    div = tree.find("tei:text/tei:body/tei:div", NS)

    groups = []  # same cut as xslt/editions.xsl: body/div children, starting at each pb
    for child in div:
        if tag(child) == t_("pb"):
            groups.append((child, []))
        elif tag(child) and groups:  # content before the first pb is not shown (build warning)
            groups[-1][1].append(child)

    for n, (pb, content) in enumerate(groups, start=1):
        orig, reg = LayerText("orig"), LayerText("reg")
        for el in content:
            for layer in (orig, reg):
                layer.walk(el)
                layer.parts.append(" ")
        lemmas, langs, refs = [], [], []
        entities = {f: [] for f in ENTITY_FIELDS.values()}
        for el in content:
            lang = LANG_LABELS.get(el.get(XML_LANG), el.get(XML_LANG))
            if lang and lang not in langs:
                langs.append(lang)
            for sub in el.iter():
                t = tag(sub)
                if t == t_("w"):
                    lemma = clean_lemma(sub.get("lemma"))
                    if lemma and lemma not in lemmas:
                        lemmas.append(lemma)
                elif t == t_("foreign"):
                    lang = LANG_LABELS.get(sub.get(XML_LANG), sub.get(XML_LANG))
                    if lang and lang not in langs:
                        langs.append(lang)
                elif t in ENTITY_TAGS and sub.get("ref"):
                    ref = sub.get("ref").split()[0].lstrip("#")
                    field = ENTITY_FIELDS.get(ref.split("-")[0])
                    if field and ref in labels:  # unresolved refs are not indexed (as in the reading view)
                        if labels[ref] not in entities[field]:
                            entities[field].append(labels[ref])
                        if f"{ref}|{labels[ref]}" not in refs:
                            refs.append(f"{ref}|{labels[ref]}")
        printed = re.match(r"^#f\d+-(.+)$", pb.get("corresp") or "")
        if printed and printed.group(1) != "np":
            printed = printed.group(1)
        else:
            numbering = next((el for el in content
                              if tag(el) == t_("fw") and el.get("type") == "NumberingZone"), None)
            printed = text_of(numbering) if numbering is not None else ""
        record = {
            "id": f"{doc_id}-page-{n}",
            "doc_id": doc_id,
            "doc_title": title,
            "author": author,
            "page_n": n,
            "printed": printed,
            "url": f"{doc_id}-page-{n}.html",
            "text_mod": reg.value(),
            "text_orig": orig.value(),
            "lemmas": lemmas,
            "langs": langs,
            "has_note": any(tag(el) == t_("note") for el in content),
            "entity_refs": refs,
            **entities,
        }
        if year:
            record["date"] = int(year.group(0))
        yield record


def schema(name):
    def facet(field, kind="string[]"):
        return {"name": field, "type": kind, "facet": True, "optional": True}

    return {
        "name": name,
        "default_sorting_field": "page_n",
        # l'éloquence -> l / éloquence ; celles-ci -> celles / ci (Typesense only accepts
        # one-byte separators: the typographic apostrophe is normalised in LayerText.value)
        "token_separators": ["'", "-"],
        "metadata": {"description": "Grand Siecle demo: one document per printed page"},
        "fields": [
            {"name": "doc_id", "type": "string", "facet": True},
            {"name": "doc_title", "type": "string", "facet": True},
            {"name": "author", "type": "string", "facet": True},
            facet("date", "int32"),
            {"name": "page_n", "type": "int32", "sort": True},
            {"name": "printed", "type": "string", "index": False, "optional": True},
            {"name": "url", "type": "string", "index": False},
            # no "locale": with locale "fr" Typesense keeps diacritics (eloquence != éloquence)
            {"name": "text_mod", "type": "string"},
            {"name": "text_orig", "type": "string"},
            {"name": "lemmas", "type": "string[]"},
            facet("langs"),
            {"name": "has_note", "type": "bool", "facet": True},
            {"name": "entity_refs", "type": "string[]", "index": False, "optional": True},
            *[facet(f) for f in ENTITY_FIELDS.values()],
        ],
    }


def main():
    name = env("TYPESENSE_COLLECTION", "grand-siecle-dse")
    node = {"host": env("TYPESENSE_HOST", "localhost"), "port": env("TYPESENSE_PORT", "8108"),
            "protocol": env("TYPESENSE_PROTOCOL", "http")}
    public = {"host": env("TYPESENSE_PUBLIC_HOST", node["host"]),
              "port": env("TYPESENSE_PUBLIC_PORT", node["port"]),
              "protocol": env("TYPESENSE_PUBLIC_PROTOCOL", node["protocol"])}
    client = typesense.Client({"nodes": [node], "api_key": env("TYPESENSE_API_KEY"),
                               "connection_timeout_seconds": int(env("TYPESENSE_TIMEOUT", "120"))})
    t0 = time.perf_counter()
    labels = register_labels()
    files = sorted(glob.glob(str(ROOT / "data" / "editions" / "*.xml")))
    if not files:
        sys.exit("ERROR: data/editions is empty, run pyscripts/fetch_data.py first")
    records = [r for f in files for r in page_records(f, labels)]
    t1 = time.perf_counter()

    # full rebuild, as in the template (search is unavailable during the few seconds of the import)
    try:
        client.collections[name].delete()
    except ObjectNotFound:
        pass
    client.collections.create(schema(name))
    results = client.collections[name].documents.import_(records, {"action": "create"}, batch_size=200)
    failed = [r for r in results if not r.get("success")]
    if failed:
        sys.exit(f"ERROR: {len(failed)} documents rejected, first: {failed[0]}")
    count = client.collections[name].retrieve()["num_documents"]
    t2 = time.perf_counter()

    # search-only key restricted to this collection; keys previously created by this script are revoked
    for key in client.keys.retrieve().get("keys", []):
        if key.get("description") == KEY_DESCRIPTION:
            client.keys[key["id"]].delete()
    search_key = client.keys.create({"description": KEY_DESCRIPTION, "actions": ["documents:search"],
                                     "collections": [name]})["value"]
    CONFIG_JS.write_text(
        "/* Generated by pyscripts/make_ts_index.py: search-only key, do not edit. */\n"
        "window.GS_SEARCH_CONFIG = "
        + json.dumps({"collection": name, "apiKey": search_key, "nodes": [public]}, indent=1) + ";\n",
        encoding="utf-8")

    print(f"{len(records)} page records built in {t1 - t0:.2f} s, sent and indexed in {t2 - t1:.2f} s; "
          f"collection '{name}': {count} documents")
    print(f"search-only key -> {CONFIG_JS.relative_to(ROOT)} (actions: documents:search; collections: [{name}])")


if __name__ == "__main__":
    main()
